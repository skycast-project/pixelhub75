#pragma once

// Записывает "заводские" настройки в глобальные переменные и сохраняет их
void setDefaultConfig();

// Загружает /config.json из LittleFS в глобальные переменные
// (если файла нет/битый — вызывает setDefaultConfig())
void loadConfig();

// Сохраняет текущие глобальные настройки в /config.json
// и дублирует их в резервную копию во флеш-памяти (NVS) - копия переживает
// "Upload Filesystem Image", который стирает файловую систему.
void saveConfig();

// Удаляет резервную копию настроек из NVS (для "сброса к заводским":
// после этого удаление /config.json снова даёт настройки по умолчанию).
void clearConfigBackup();
