#pragma once
#include <Arduino.h>

// Синхронный запрос погоды (блокирует до ~8-24 сек при сбое сети).
// Используется ТОЛЬКО в setup(), до запуска watchdog и анимаций.
// Заполняет глобальные переменные погоды и weatherString/weatherStringZ.
bool fetchWeather();

// ===== АСИНХРОННЫЙ РЕЖИМ (для loop()) =====
// Сеть опрашивается в отдельной FreeRTOS-задаче, поэтому бегущая строка
// и остальная анимация не замирают, даже если сервер не отвечает.
// Глобальные переменные погоды обновляются ТОЛЬКО при успешном разборе
// ответа и только из основного потока (внутри pollWeatherResult), поэтому
// при сбое на экране остаются последние удачные данные, а не нули.

// Создаёт фоновую задачу. Вызвать один раз в setup(), после подключения к Wi-Fi.
void startWeatherTask();

// Просит задачу обновить погоду. Возвращает false, если запрос уже идёт,
// задача не запущена или нет Wi-Fi (тогда просто повторить позже).
bool requestWeatherUpdate();

// Вызывать в loop() на каждой итерации. Если фоновый запрос завершился -
// применяет результат (разбор JSON, обновление глобальных переменных),
// возвращает true и кладёт в success итог (true = данные обновлены).
// Если результата ещё нет - возвращает false, ничего не делает.
bool pollWeatherResult(bool &success);
