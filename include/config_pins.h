//  I2C — датчик BME280 / BMP280 (экран «Дома»)
// ============================================================================
#define SENSOR_SDA_PIN  21
#define SENSOR_SCL_PIN  22

// ============================================================================
//  SD-карта (SPI) и ЦАП PCM5102 (I2S) — на классическом ESP32 не используются.
// ============================================================================
#define SD_CS_PIN    -1
#define SD_MOSI_PIN  -1
#define SD_MISO_PIN  -1
#define SD_SCK_PIN   -1
#define I2S_BCLK_PIN -1
#define I2S_LRC_PIN  -1
#define I2S_DOUT_PIN -1

