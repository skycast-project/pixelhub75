#pragma once

// ============================================================================
//  CONFIG_PINS.H — ПИНЫ ПО УМОЛЧАНИЮ (классический ESP32)
//
//  Это значения по умолчанию. Пины матрицы можно менять без пересборки:
//  веб-интерфейс → «Настройки» → «Пины матрицы» (/settings/pins).
//  Сохранённые значения хранятся в NVS и имеют приоритет над этим файлом.
//
//  ВАЖНО для классического ESP32:
//     - GPIO 6..11 заняты флеш-памятью, их нельзя использовать;
//     - GPIO 34..39 только на вход, для выходов не годятся;
//     - GPIO 12 (MTDI) влияет на напряжение флеша при старте - если
//       матрица не зажигается, попробуйте перенести A_PIN на другой пин.
// ============================================================================

// ============================================================================
//  МАТРИЦА HUB75 (64x32, 1/16 scan)
// ============================================================================
#define R1_PIN   4
#define G1_PIN   2
#define B1_PIN   5
#define R2_PIN   13
#define G2_PIN   14
#define B2_PIN   23
#define A_PIN    12
#define B_PIN    16
#define C_PIN    17
#define D_PIN    18
