#pragma once
#include <Arduino.h>

// ============================================================
// Список радиостанций - хранится в /stations.json на LittleFS.
// Формат: [{"name":"Радио Х","url":"http://..."}, ...]
// В отличие от оригинала (жёстко зашитый список в playlist.h),
// список редактируется через веб - вручную ИЛИ импортом плейлиста
// M3U/PLS целиком.
// ============================================================

#define MAX_STATIONS 50

struct StationInfo {
  String name;
  String url;
};

// Загружает список из /stations.json в память. Если файла нет -
// список остаётся пустым (не ошибка - просто "станций пока нет").
// Вызывать один раз, из initRadio().
void loadStations();

// Сохраняет текущий список станций обратно в /stations.json.
void saveStations();

int getStationCount();

// Возвращает станцию по индексу. Если индекс вне диапазона -
// возвращает пустую структуру (name/url == "").
StationInfo getStation(int index);

// Добавляет станцию в конец списка и сохраняет. false, если
// name/url пустые или список уже заполнен (MAX_STATIONS).
bool addStation(const String &name, const String &url);

// Удаляет станцию по индексу (сдвигает остальные), сохраняет.
bool removeStation(int index);

// Разбирает содержимое M3U (#EXTM3U/#EXTINF/URL) или PLS
// (TitleN=/FileN=) плейлиста, переданное целиком одной строкой
// (как есть из загруженного файла), и добавляет найденные станции
// в конец списка. Не строгий парсер - вытаскивает то, что нужно
// из типичных плейлистов радиостанций. Возвращает число добавленных.
int importPlaylist(const String &content);
