#pragma once

#include <Arduino.h>

// Стартовая заставка-тест матрицы: рамки, наплывающие от края к центру,
// поочерёдно красным/зелёным/синим - реконструкция классического
// теста RGB-каналов HUB75-матрицы (проверка, что цвета/провода не
// перепутаны). Вызывать один раз в setup(), сразу после initDisplay(),
// ДО подключения к Wi-Fi. Блокирующая (delay() внутри) - это нормально,
// так как выполняется один раз при старте, до входа в loop().
void showStartupTestPattern();

// Стартовый логотип-заставка: название проекта выезжает снизу вверх,
// держится на экране, затем "взрывается" на отдельные пиксели, которые
// разлетаются в случайные стороны и гаснут по мере разлёта. Не копирует
// анимацию оригинала Шилова (getAnim()) - полностью своя, взамен неё.
// Карта зажжённых пикселей текста строится через временный монохромный
// буфер в памяти (GFXcanvas1), поэтому эффект одинаково работает для
// любого текста/шрифта, ничего не подгоняется вручную под конкретные
// координаты. Блокирующая (как и showStartupTestPattern) - вызывать
// один раз в setup(), сразу после неё.
void showStartupLogoAnimation();

// Один кадр графической анимации "идёт подключение" (пульсирующие
// кольца-радар, без единого слова текста) - вызывать МНОГОКРАТНО, в
// каждой итерации цикла ожидания WiFi.begin() в main.cpp, пока не
// подключимся или не истечёт таймаут. Сама функция не блокирует и не
// хранит состояние между вызовами - вся анимация считается через millis().
void updateWifiConnectingAnimation();

// Итоговый экран результата подключения - вызывается один раз ПОСЛЕ
// цикла ожидания в setup(). connected=true -> только цифры IP-адреса
// (зелёным, крупно, по центру, без слов "Wi-Fi OK"); connected=false ->
// графический крестик (тоже без текста, ipStr в этом случае игнорируется).
void showWifiResultScreen(bool connected, const String &ipStr);

// Экран режима настройки Wi-Fi - показывается, когда подключиться к
// сохранённой сети не удалось и устройство подняло свою точку доступа
// (captive portal). Английский текст на всю матрицу: "No WiFi!" (красный),
// "Connect to" (белый) и имя точки доступа, окрашенное радужной волной
// (как логотип на заставке). Рисует первый кадр.
void showApModeScreen(const String &apSsid);

// Обновляет кадр волны на экране точки доступа (сама ограничивает частоту,
// ~25 кадров/с). Вызывать из loop() каждую итерацию, пока поднята точка
// доступа (см. main.cpp). Без вызова экран остаётся статичным.
void updateApModeScreen();

// Инициализация HUB75-матрицы (пины, DMA, яркость)
bool initDisplay();

// Синхронизация времени по NTP
bool initTime();

// Считывает текущее время из системных часов ESP32 в глобальные переменные
void updateTime();

// Если autoBrightnessEnabled включён - выставляет displayBrightness днём
// (между восходом и закатом) и nightBrightness ночью. Восход/закат
// берутся из последнего ответа Open-Meteo (см. weather.cpp), поэтому
// граница дня/ночи сама смещается вместе со временем года.
// Вызывать раз в секунду и сразу после смены настроек яркости.
void applyAutoBrightness();
